const getNestedValue = (source, path) =>
  path.split(".").reduce((current, part) => (current ? current[part] : undefined), source);

const formatTemplate = (value, params = {}) =>
  value.replace(/\{(\w+)\}/g, (_, key) => `${params[key] ?? ""}`);

export const createTranslator = (language) => {
  const locale = TRANSLATIONS[language] ? language : FALLBACK_LANGUAGE;
  const bundle = TRANSLATIONS[locale];

  return (path, params = {}) => {
    const value = getNestedValue(bundle, path);

    if (typeof value === "function") {
      return value(params);
    }

    if (typeof value === "string") {
      return formatTemplate(value, params);
    }

    return path;
  };
};

