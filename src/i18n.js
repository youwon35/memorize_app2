const getNestedValue = (source, path) =>
  path.split(".").reduce((current, part) => (current ? current[part] : undefined), source);

const formatTemplate = (value, params = {}) =>
  value.replace(/\{(\w+)\}/g, (_, key) => `${params[key] ?? ""}`);

export const createTranslator = (language) => {
  const locale = TRANSLATIONS[language] ? language : "ko";
  const bundle = TRANSLATIONS[locale];

  return (path, params = {}) => {
    const value = getNestedValue(bundle, path);

    if (typeof value === "function") {
      return value(params);
    }

    if (typeof value === "string") {
      return formatTemplate(value, params);
    }

    return path;
  };
};

export const normalizeSupportCategory = (value) =>
  SUPPORT_CATEGORY_VALUE_MAP[value] ?? "other";

export const normalizeSupportStatus = (value) =>
  SUPPORT_STATUS_VALUE_MAP[value] ?? "received";

export const formatDateTimeForLanguage = (timestamp, language) => {
  const date = timestamp ? new Date(timestamp) : new Date();

  if (Number.isNaN(date.getTime())) {
    return createTranslator(language)("common.justNow");
  }

  return new Intl.DateTimeFormat(LANGUAGE_LOCALES[language] ?? LANGUAGE_LOCALES.ko, {
    month: "numeric",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(date);
};

export const formatSessionLabelForLanguage = (timestamp, language) => {
  const date = timestamp ? new Date(timestamp) : new Date();

  if (Number.isNaN(date.getTime())) {
    return formatDateTimeForLanguage(timestamp, language);
  }

  return new Intl.DateTimeFormat(LANGUAGE_LOCALES[language] ?? LANGUAGE_LOCALES.ko, {
    month: "numeric",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(date);
};

export const getPreferredLanguage = () => {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale?.toLowerCase?.() ?? "";

    if (locale.startsWith("en")) {
      return "en";
    }

    if (locale.startsWith("ja")) {
      return "ja";
    }
  } catch {
    // Fallback to Korean below.
  }

  return "ko";
};
